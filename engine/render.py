"""Renderer: Rule lists -> filter text.

WHAT: Writes one Show/Hide block per rule, and assembles the per-band file and the AreaLevel
      file (all bands in one file, each block limited by AreaLevel).
WHY:  All styling decisions of .docs/visual_and_sound_guide.md live here,
      driven by structure.toml: size and volume from the importance level, colours from the
      category, background = black ([style] default_background), inverse on level 5, sound id =
      family, minimap icon = category colour + family shape + size by volume, beam = category
      colour.
HOW:  Sections keep their order; inside the AreaLevel file a section's band blocks stay together.
      Output is deterministic (no timestamps), so two builds can be diffed.
"""
from engine.logsetup import get_logger

LOGGER = get_logger("render")
INDENT = "    "


# ----------------------------------------------------------------------------------------------
# Colours
# ----------------------------------------------------------------------------------------------
def colours(rule, structure):
    """(text, border, background, named colour) of a visible rule; None where not set."""
    try:
        style = structure["style"]
        category = structure["categories"].get(rule.category, {}) if rule.category else {}
        text, border = category.get("text"), rule.border or category.get("border")
        background = category.get("background") or style["default_background"]
        if structure["importance"][str(rule.level)].get("inverse") and text:
            text, background = style["inverse_text"], text
        return text, border, background, category.get("icon")
    except Exception:
        LOGGER.exception("colours failed: %r", rule)
        raise


# ----------------------------------------------------------------------------------------------
# Blocks
# ----------------------------------------------------------------------------------------------
def condition_lines(rule, area_level):
    try:
        lines = []
        if area_level:
            lines.append(f"AreaLevel >= {rule.band['min']}")
            lines.append(f"AreaLevel <= {rule.band['max']}")
        for condition in rule.conditions:
            values = " ".join(f'"{value}"' if isinstance(value, str) and condition.keyword in ("BaseType", "Class")
                              else str(value) for value in condition.values)
            operator = f"{condition.operator} " if condition.operator else ""
            lines.append(f"{condition.keyword} {operator}{values}")
        return lines
    except Exception:
        LOGGER.exception("condition_lines failed: %r", rule)
        raise


def style_lines(rule, structure):
    try:
        importance = structure["importance"][str(rule.level)]
        text, border, background, named = colours(rule, structure)
        lines = [f"SetFontSize {importance['font_size']}"]
        lines += [f"SetTextColor {text}"] if text else []
        lines += [f"SetBorderColor {border}"] if border and not rule.hide_border else []
        lines.append(f"SetBackgroundColor {background}")
        volume = importance["volume"]
        if volume and rule.family and not rule.silent:
            lines.append(f"PlayAlertSound {rule.family} {volume}")
        if (rule.beam or rule.icon) and not named:
            raise ValueError(f"beam/icon without a named colour (category {rule.category!r})")
        if rule.beam:
            lines.append(f"PlayEffect {named}")
        if rule.icon:
            size = structure["icon_size_by_volume"][str(volume)]
            shape = structure["families"][rule.family]["icon_shape"]
            lines.append(f"MinimapIcon {size} {named} {shape}")
        return lines
    except Exception:
        LOGGER.exception("style_lines failed: %r", rule)
        raise


def render_rule(rule, structure, area_level):
    try:
        lines = condition_lines(rule, area_level)
        if rule.visible:
            lines += style_lines(rule, structure)
        keyword = "Show" if rule.visible else "Hide"
        return "\n".join([keyword] + [INDENT + line for line in lines]) + "\n"
    except Exception:
        LOGGER.exception("render_rule failed: %r", rule)
        raise


# ----------------------------------------------------------------------------------------------
# Files
# ----------------------------------------------------------------------------------------------
def header_lines(meta, scope):
    try:
        return [f"# PoE2 loot filter {meta['filter_version']} - {scope}",
                f"# Generated by engine.build from RePoE {meta['repoe_version']}; do not edit by hand.",
                f"# Sections: {', '.join(meta['sections'])}", ""]
    except Exception:
        LOGGER.exception("header_lines failed: %r", meta)
        raise


def render_file(sections, structure, meta, band=None):
    """Filter text; band=None -> the AreaLevel file with every band, else one band's file."""
    try:
        scope = "all bands (AreaLevel)" if band is None else f"band {band['min']}-{band['max']}"
        parts = ["\n".join(header_lines(meta, scope))]
        for name, rules in sections:
            selected = [rule for rule in rules if band is None or rule.band == band]
            parts.append(f"# ===== {name.upper()} ===== #\n")
            parts += [render_rule(rule, structure, area_level=band is None) for rule in selected]
        return "\n".join(parts)
    except Exception:
        LOGGER.exception("render_file failed: band=%r", band)
        raise
